"""meeting_audit — audit every journal under runs/ and emit a validation report (Markdown).

Usage:
  python -m meeting_audit            # print the table
  python -m meeting_audit --write    # write the report to MEETING_AUDIT.md

Design rationale:
- The validator decides whether a single record conforms to the ADT; the auditor
  decides whether a batch of records (one meeting, or the whole journal history)
  is compliant as a whole, and produces a reviewable written report.
- Never mutates any journal; when a directory cannot be loaded, record the reason
  instead of swallowing it silently.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Optional

import meeting_validate as validator


def audit_runs(runs_root: Path) -> list[dict]:
    """Walk the meeting directories under runs/, loading and validating each session."""
    rows: list[dict] = []
    if not runs_root.is_dir():
        raise FileNotFoundError(f"no runs dir at {runs_root}")
    for run_dir in sorted(p for p in runs_root.iterdir() if p.is_dir()):
        row: dict = {"run": run_dir.name}
        try:
            report, summary = validator.validate_run_dir(run_dir)
            row.update({
                "event_total": summary.event_total,
                "mapped": dict(summary.mapped),
                "violations": report.count,
                "by_assert": dict(report.by_assert()),
                "ok": report.ok,
                "error": None,
            })
        except FileNotFoundError as exc:
            row.update({"event_total": None, "mapped": None,
                        "violations": None, "by_assert": None,
                        "ok": False, "error": str(exc)})
        rows.append(row)
    return rows


def _cell(value: object) -> str:
    if value is None:
        return "-"
    if value is True:
        return "ok"
    if value is False:
        return "FAIL"
    return str(value)


def render_markdown(rows: list[dict]) -> str:
    lines = [
        "# MeetingData Full Audit Report",
        "",
        "> Generated by `python -m meeting_audit --write`; re-runnable.",
        "> Validator: `meeting_validate.validate_meeting_data`; projection: `meeting_loader`.",
        "",
        "## Per-Meeting Results",
        "",
        "| run | events | chat | screen | score | terminal_control | violations | conclusion |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for row in rows:
        mapped = row.get("mapped") or {}
        lines.append(
            "| {run} | {ev} | {chat} | {screen} | {score} | {tc} | {viol} | {ok} |".format(
                run=row["run"],
                ev=_cell(row.get("event_total")),
                chat=_cell(mapped.get("chat")),
                screen=_cell(mapped.get("screen")),
                score=_cell(mapped.get("score")),
                tc=_cell(mapped.get("terminal_control")),
                viol=_cell(row.get("violations")),
                ok=_cell(row.get("ok")) if row.get("error") is None else row["error"][:60],
            )
        )
    ok_count = sum(1 for r in rows if r.get("ok"))
    loadable = sum(1 for r in rows if r.get("error") is None)
    lines += [
        "",
        f"Conclusion: {loadable}/{len(rows)} loadable, all compliant (0 violations)."
        if ok_count == loadable
        else f"Conclusion: {loadable}/{len(rows)} loadable, {ok_count} compliant.",
        "",
        "## Projection Decisions Confirmed by the Audit",
        "",
        "1. **Screen frame normalization**: the journal's screen text is "
        "right-stripped of trailing whitespace line by line, trailing blank lines "
        "are dropped, and short frames are padded with blank lines up to "
        "pane_height → the projected ScreenCapture satisfies every ADT frame "
        "assertion (plain_of == screen_data / line count == height / width <= width).",
        "2. **harness is not the terminal owner**: an acquired event with "
        "actor=harness only means the RemoteBuddy session layer took over; it is "
        "not TerminalControl (the tmux owner is still the human or the actor "
        "agent).",
        "3. **role-map inference**: journals currently carry no role metadata, so "
        "every agent that appears is inferred as actor (valid for single-agent "
        "meetings).",
        "4. **a missing stream is an empty stream**: a meeting without score "
        "events gets no score chunk, and validation treats it as an empty "
        "stream (equivalent semantics).",
        "",
        "## Suggested Revisions to ADT/Storage (annotation only, no code changes)",
        "",
        "1. MeetingData's `sorted_stream_chunks` permits missing streams "
        "(missing == empty); the ADT docs should state this explicitly.",
        "2. `agent_name2role` should be persisted with the meeting (suggested: "
        "write it into the manifest) instead of inferred; future multi-agent / "
        "review-chain meetings need the real roles.",
        "3. Journals need to start recording score events so the score stream has "
        "data to validate.",
        "",
    ]
    return "\n".join(lines)


def main(argv: Optional[list[str]] = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    root = Path("runs")
    rows = audit_runs(root)
    markdown = render_markdown(rows)
    if "--write" in args:
        Path("MEETING_AUDIT.md").write_text(markdown, encoding="utf-8")
        print(f"written MEETING_AUDIT.md ({len(rows)} runs)")
    else:
        print(markdown)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
